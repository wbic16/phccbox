with open(os.path.join(OUT, "lit_exoconsole.h"), "w") as f:
    f.write("/* generated by gen_literals.py -- do not edit */\n")
    f.write("static const char *const EXO_PERSONAS[] = {%s, 0};\n" % ", ".join(cstr(p) for p in plist))
    f.write("static const char *const EXO_QUOTES[] = {%s, 0};\n" % ", ".join(cstr(q) for q in qlist))
print("wrote lit_exoconsole.h")
print("ALL OK")
