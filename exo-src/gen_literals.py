#!/usr/bin/env python3
"""Extract literal material (heredocs, tables) from the exocortical repo
files and emit C headers. Guarantees byte-fidelity of embedded texts."""
import re, os, sys

SRC = os.path.expanduser("~/workspace/exocortical-fresh")
OUT = os.path.expanduser("~/workspace/phccbox/exo-src/gen")
os.makedirs(OUT, exist_ok=True)

def read(name):
    with open(os.path.join(SRC, name), "r", encoding="utf-8", errors="surrogateescape") as f:
        return f.read()

def cstr(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"': out.append('\\"')
        elif ch == '\\': out.append('\\\\')
        elif ch == '\n': out.append('\\n')
        elif ch == '\t': out.append('\\t')
        elif 32 <= o < 127: out.append(ch)
        else: out.append('\\%03o' % o)
    return '"' + ''.join(out) + '"'

def emit(name, items):
    """items: list of (cname, python-string) -> static const char * arrays"""
    with open(os.path.join(OUT, name), "w") as f:
        f.write("/* generated by gen_literals.py from wbic16/exocortical @ 0872ca2a -- do not edit */\n")
        for cname, s in items:
            f.write("static const char %s[] = %s;\n" % (cname, cstr(s)))
    print("wrote", name)

def heredoc(text, start_marker, end_marker="EOF"):
    """Return the raw text between the line containing start_marker's '<<'
    heredoc start and the terminator line."""
    lines = text.split("\n")
    for i, ln in enumerate(lines):
        if start_marker in ln and "<<" in ln:
            j = i + 1
            body = []
            term = end_marker
            m = re.search(r"<<\s*'?(\w+)'?", ln)
            if m: term = m.group(1)
            while j < len(lines) and lines[j] != term:
                body.append(lines[j]); j += 1
            assert j < len(lines), "heredoc %s not terminated" % start_marker
            raw = "\n".join(body) + "\n"
            # bash rule for UNQUOTED heredocs: backslash-newline is a line
            # continuation and is removed (the squid.conf ssl-bump header
            # relies on it). Quoted heredocs (<<'EOF') keep bytes raw.
            if "'" not in ln.split("<<", 1)[1]:
                raw = raw.replace("\\\n", "")
            return raw
    raise AssertionError("heredoc not found: " + start_marker)

def tmpl(s):
    """Convert shell ${VAR} / $VAR expansions into %%VAR%% tokens."""
    s = s.replace("%%", "\x01")
    s = re.sub(r"\$\{([A-Za-z_][A-Za-z0-9_]*)\}", r"%%\1%%", s)
    s = re.sub(r"\$([A-Za-z_][A-Za-z0-9_]*)", r"%%\1%%", s)
    return s.replace("\x01", "%%")

# ---------------------------------------------------------------- squid server
srv = read("provision-squid-server.sh")
squid_conf = heredoc(srv, "cat > /etc/squid/squid.conf")
assert "Ranch Choir Aggressive Caching Proxy" in squid_conf
emit("lit_squid.h", [("SQUID_CONF_TMPL", tmpl(squid_conf))])

# ---------------------------------------------------------------- nfs blocks
ns = read("nfs-provision-server.sh")
exports = heredoc(ns, "cat >> /etc/exports")
assert "Ranch Choir NFS Exports" in exports
nc = read("nfs-provision-client.sh")
fstab = heredoc(nc, "cat >> /etc/fstab")
assert "Ranch Choir NFS" in fstab
emit("lit_nfs.h", [("NFS_EXPORTS_TMPL", tmpl(exports)), ("NFS_FSTAB_TMPL", tmpl(fstab))])

# ---------------------------------------------------------------- browser sandbox profile
bs = read("enable-browser-sandbox.sh")
profile = heredoc(bs, 'cat > "$PROFILE_FILE"')
assert "Playwright-managed Chrome" in profile
emit("lit_sandbox.h", [("SANDBOX_PROFILE_TMPL", tmpl(profile))])

# ---------------------------------------------------------------- usb ssd fixup
usb = read("usb-ssd-fixup.sh")
sysctl_min = heredoc(usb, "99-minimize-disk-io.conf")
journald = heredoc(usb, "volatile.conf")
assert "vm.swappiness = 1" in sysctl_min and "Storage=volatile" in journald
emit("lit_usb.h", [("USB_SYSCTL_CONF", sysctl_min), ("USB_JOURNALD_CONF", journald)])

# ---------------------------------------------------------------- optimize-llm
opt = read("optimize-llm-inference.sh")
llm_sysctl = heredoc(opt, 'tee "$SYSCTL_CONF"')
llm_udev = heredoc(opt, 'tee "$UDEV_RULE"')
llm_override = heredoc(opt, 'tee "${OLLAMA_OVERRIDE}/exocortical.conf"')
assert "vm.swappiness=60" in llm_sysctl and "mq-deadline" in llm_udev and "OLLAMA_HOST" in llm_override
emit("lit_llm.h", [("LLM_SYSCTL_CONF", llm_sysctl), ("LLM_UDEV_RULE", llm_udev),
                  ("LLM_OLLAMA_OVERRIDE_TMPL", tmpl(llm_override))])

# ---------------------------------------------------------------- squid client
sc = read("provision-squid-client.sh")
apt_proxy = heredoc(sc, "02ranch-proxy")
ollama_proxy = heredoc(sc, "proxy.conf")
profiled = heredoc(sc, "ranch-proxy.sh")
environ = heredoc(sc, "cat >> /etc/environment")
pipconf = heredoc(sc, "pip.conf")
for nm, body in [("apt", apt_proxy), ("ollama", ollama_proxy), ("profiled", profiled),
                 ("environ", environ), ("pip", pipconf)]:
    assert "PROXY" in body or "proxy" in body, nm
emit("lit_squidclient.h", [("SQ_APT_PROXY_TMPL", tmpl(apt_proxy)),
                           ("SQ_OLLAMA_PROXY_TMPL", tmpl(ollama_proxy)),
                           ("SQ_PROFILED_TMPL", tmpl(profiled)),
                           ("SQ_ENVIRON_TMPL", tmpl(environ)),
                           ("SQ_PIP_CONF_TMPL", tmpl(pipconf))])

# ---------------------------------------------------------------- setup.sh pieces
su = read("setup.sh")
dns = heredoc(su, "fallback.conf")
assert "FallbackDNS" in dns
# apt package list: lines between 'sudo apt install -y --no-install-recommends \' and the snap comment
m = re.search(r"sudo apt install -y --no-install-recommends \\\n(.*?)\n\n", su, re.S)
pkgs = []
for ln in m.group(1).split("\n"):
    pkgs += ln.replace("\\", " ").split()
crates = re.search(r"cargo_crates=\(([^)]*)\)", su).group(1).split()
repos = re.findall(r"^clone_repo ([a-zA-Z0-9_.\-]+)$", su, re.M)
print("setup pkgs:", len(pkgs), "crates:", crates, "repos:", len(repos))
with open(os.path.join(OUT, "lit_setup.h"), "w") as f:
    f.write("/* generated by gen_literals.py -- do not edit */\n")
    f.write("static const char SETUP_DNS_CONF[] = %s;\n" % cstr(dns))
    f.write("static const char *const SETUP_PKGS[] = {%s, 0};\n" % ", ".join(cstr(p) for p in pkgs))
    f.write("static const char *const SETUP_CRATES[] = {%s, 0};\n" % ", ".join(cstr(c) for c in crates))
    f.write("static const char *const SETUP_REPOS[] = {%s, 0};\n" % ", ".join(cstr(r) for r in repos))
print("wrote lit_setup.h")

# ---------------------------------------------------------------- tb-setup map + unit
tb = read("tb-setup.sh")
pairs = re.findall(r"\[([a-z0-9\-]+)\]=(10\.53\.\d+\.\d+)", tb)
assert len(pairs) == 26, len(pairs)
unit = heredoc(tb, "tb-fabric.service")
assert "Mirrorborn USB4 fabric setup" in unit
with open(os.path.join(OUT, "lit_tb.h"), "w") as f:
    f.write("/* generated by gen_literals.py -- do not edit */\n")
    f.write("static const char TB_FABRIC_UNIT[] = %s;\n" % cstr(unit))
    f.write("static const char *const TB_MAP[] = {%s, 0};\n" %
            ", ".join("%s, %s" % (cstr(h), cstr(ip)) for h, ip in pairs))
print("wrote lit_tb.h", len(pairs))

# ---------------------------------------------------------------- install-keys
ik = read("install-keys.sh")
keys = re.findall(r'"(ssh-ed25519 [A-Za-z0-9+/=]+ [^"]*)"', ik)
assert len(keys) == 12, len(keys)
with open(os.path.join(OUT, "lit_keys.h"), "w") as f:
    f.write("/* generated by gen_literals.py -- do not edit */\n")
    f.write("static const char *const MIRRORBORN_KEYS[] = {%s, 0};\n" % ", ".join(cstr(k) for k in keys))
print("wrote lit_keys.h", len(keys))

# ---------------------------------------------------------------- ports.html personas + hosts
ports = read("ports.html")
host_sec = ports.split('<select id="host">')[1].split('</select>')[0]
hosts = re.findall(r'<option value="([^"]+)">([^<]+)</option>', host_sec)
port_sec = ports.split('<select id="port">')[1].split('</select>')[0]
personas = re.findall(r'<option value="(\d+)">([^<]+)</option>', port_sec)
print("ports hosts:", hosts)
print("ports personas:", len(personas))
with open(os.path.join(OUT, "lit_ports.h"), "w") as f:
    f.write("/* generated by gen_literals.py -- do not edit */\n")
    f.write("static const char *const PORTS_HOSTS[] = {%s, 0};\n" %
            ", ".join("%s, %s" % (cstr(v), cstr(t)) for v, t in hosts))
    f.write("static const char *const PORTS_PERSONAS[] = {%s, 0};\n" %
            ", ".join("%s, %s" % (cstr(v), cstr(t)) for v, t in personas))
print("wrote lit_ports.h")

# ---------------------------------------------------------------- exo.js data
exojs = read("exo.js")
